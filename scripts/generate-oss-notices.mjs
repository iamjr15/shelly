#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const check = process.argv.includes("--check");
const noticesPath = path.join(repo, "docs/open-source-notices.json");
const androidPath = path.join(
  repo,
  "apps/android/app/src/main/kotlin/app/shelly/android/features/settings/OpenSourceLicensesScreen.kt",
);

const notices = JSON.parse(fs.readFileSync(noticesPath, "utf8"));
validateNotices(notices);

writeOrCheck(androidPath, kotlinSource(notices));

console.log(
  check
    ? "open-source notice screens are current"
    : "generated open-source notice screens",
);

function writeOrCheck(file, contents) {
  if (check) {
    const current = fs.readFileSync(file, "utf8");
    if (current !== contents) {
      console.error(`${path.relative(repo, file)} is not current; run npm run generate:oss-notices`);
      process.exitCode = 1;
    }
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
}

function validateNotices(items) {
  const termlib = items.find((item) => item.name === "ConnectBot termlib");
  if (!termlib) {
    console.error("docs/open-source-notices.json is missing ConnectBot termlib");
    process.exit(1);
  }
  if (termlib.license !== "Apache-2.0") {
    console.error("ConnectBot termlib must be listed as Apache-2.0; libvterm is the MIT-licensed component");
    process.exit(1);
  }
}

function kotlinSource(items) {
  return `// Generated by scripts/generate-oss-notices.mjs. Do not edit by hand.
package app.shelly.android.features.settings

import androidx.compose.foundation.layout.PaddingValues
import androidx.compose.foundation.layout.fillMaxSize
import androidx.compose.foundation.layout.padding
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.itemsIndexed
import androidx.compose.material3.Text
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import app.shelly.android.ui.components.SettingsGlyph
import app.shelly.android.ui.components.SettingsHeroBody
import app.shelly.android.ui.components.SettingsListRow
import app.shelly.android.ui.components.ShellyScreen
import app.shelly.android.ui.theme.ShellyTheme
import app.shelly.android.ui.theme.ShellyType

private data class LicenseNotice(
    val name: String,
    val license: String,
    val url: String,
)

private val licenseNotices = listOf(
${items
  .map(
    (item) =>
      `    LicenseNotice(${q(item.name)}, ${q(item.license)}, ${q(item.url)}),`,
  )
  .join("\n")}
)

@Composable
fun OpenSourceLicensesScreen(padding: PaddingValues, onBack: () -> Unit) {
    ShellyScreen(
        modifier = Modifier.padding(padding),
        hero = {
            SettingsHeroBody(
                eyebrow = "THE OPEN SOURCE\\nTHIS IS BUILT ON",
                wordmark = "OSS",
                status = "\${licenseNotices.size} notices",
                statusGlyph = SettingsGlyph.Package,
                onBack = onBack,
            )
        },
        content = {
            LazyColumn(Modifier.fillMaxSize()) {
                item {
                    Text(
                        text = "Shelly is open source. These are the primary projects used by the Android app and shared Rust core.",
                        style = ShellyType.monoSmall,
                        color = ShellyTheme.colors.textMuted,
                    )
                }
                itemsIndexed(licenseNotices) { index, notice ->
                    SettingsListRow(
                        title = notice.name,
                        value = notice.license,
                        showDivider = index != licenseNotices.lastIndex,
                    )
                }
            }
        },
    )
}
`;
}

function q(value) {
  return JSON.stringify(value);
}
